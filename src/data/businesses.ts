export const findBusiness = (slug: string) =>
  businesses.find((b) => b.slug === slug);

export const filterBusinesses = (params: {
  prefectureSlug?: string;
  citySlug?: string;
  areaSlug?: string;
  mainCategorySlug?: string;
  subCategorySlug?: string;
}) => {
  return businesses.filter((b) => {
    if (params.prefectureSlug && b.prefectureSlug !== params.prefectureSlug)
      return false;
    if (params.citySlug && b.citySlug !== params.citySlug) return false;
    if (params.areaSlug && b.areaSlug !== params.areaSlug) return false;
    if (params.mainCategorySlug && b.mainCategorySlug !== params.mainCategorySlug)
      return false;
    if (params.subCategorySlug && b.subCategorySlug !== params.subCategorySlug)
      return false;
    return b.status === "published";
  });
};

export const getFeaturedBusinesses = () =>
  businesses.filter((b) => b.isFeatured && b.status === "published");

export const getRecentBusinesses = (limit = 8) =>
  businesses
    .filter((b) => b.status === "published")
    .sort(
      (a, b) =>
        new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
    )
    .slice(0, limit);
